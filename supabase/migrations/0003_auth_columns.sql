-- Migration 0003: credentials for the admission-number login + OTP codes + crew lookup
-- (password hashes are written/read only by edge functions through the service role; the app never sees them)

alter table student add column if not exists password_hash text;
alter table student add column if not exists password_set_at timestamptz;
alter table student add column if not exists must_change_password boolean not null default true;
alter table student add column if not exists failed_logins int not null default 0;
alter table student add column if not exists locked_until timestamptz;
revoke select (password_hash) on student from authenticated, anon;

alter table staff add column if not exists password_hash text;
alter table staff add column if not exists must_change_password boolean not null default true;
revoke select (password_hash) on staff from authenticated, anon;

-- one-time codes for mobile OTP (sent by SMS provider from the edge function)
create table if not exists otp_code (
  id uuid primary key default gen_random_uuid(),
  phone text not null,
  code_hash text not null,
  purpose text not null default 'login',        -- 'login' | 'reset'
  expires_at timestamptz not null,
  attempts int not null default 0,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists otp_phone_idx on otp_code (phone, created_at desc);
alter table otp_code enable row level security;   -- no policies: service role only

-- password-reset slips generated by the office (printed or SMS'd)
create table if not exists password_slip (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references student(id) on delete cascade,
  issued_by uuid references staff(id),
  issued_at timestamptz not null default now(),
  delivered_via text                             -- 'print' | 'sms'
);
alter table password_slip enable row level security;
create policy slip_office on password_slip for select using (is_office() or has_role('class_teacher'));

-- sessions issued by the login functions, so "sign out all phones" can revoke them
create table if not exists app_session (
  id uuid primary key default gen_random_uuid(),
  student_id uuid references student(id) on delete cascade,
  staff_id uuid references staff(id) on delete cascade,
  linked_student_ids uuid[] not null default '{}',
  device_label text,
  issued_at timestamptz not null default now(),
  revoked_at timestamptz,
  check (student_id is not null or staff_id is not null)
);
create index if not exists app_session_student_idx on app_session (student_id) where revoked_at is null;
alter table app_session enable row level security;
create policy session_own on app_session for select using (student_id = any(jwt_student_ids()) or staff_id = jwt_staff_id() or is_office());

insert into school_setting (key, value) values ('password_min_length', '8') on conflict (key) do nothing;
insert into school_setting (key, value) values ('otp_ttl_minutes', '5') on conflict (key) do nothing;
insert into school_setting (key, value) values ('login_lock_after', '5') on conflict (key) do nothing;
